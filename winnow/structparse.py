# Analyst-authored patterns run against their own local data, same trust
# model as the SQL pane — but a runaway pattern shouldn't be able to be
# arbitrarily huge, and the backfill that executes it is a cancellable
# background job either way.
_MAX_REGEX_LEN = 512


def _compiled_regex(params: dict, state: dict) -> re.Pattern:
    rx = state.get("_rx")
    if rx is None:
        rx = re.compile(params.get("pattern", ""))
        state["_rx"] = rx
    return rx


def _extract_regex(value, params: dict, state: dict) -> str | None:
    if value is None:
        return None
    s = str(value)
    if not s:
        return None
    m = _compiled_regex(params, state).search(s)
    if m is None:
        return None
    # A named group is addressed by name, not by the number it happens to
    # have: an IIS or syslog pattern gets edited — a group added in the
    # middle, an alternation widened — and every numbered definition after
    # the edit would quietly start keeping a different field. The name
    # survives that; the number does not.
    name = (params.get("group_name") or "").strip()
    if name:
        try:
            return m.group(name)  # None when the group didn't participate -> NULL
        except (IndexError, re.error):
            return None
    g = int(params.get("group") or 0)
    if g == 0:
        g = 1 if m.re.groups >= 1 else 0
    try:
        return m.group(g)  # None when the group didn't participate -> NULL
    except IndexError:
        return None


def _compile_analyst_regex(pattern: str) -> "re.Pattern":
    """The one gate a derive pattern passes before it runs on anything:
    length, syntax, and rxguard's catastrophic-backtracking check — the
    same one the regex filter and search meet. The check is what makes a
    preview or a backfill safe to start: one `(\\w+\\s?)*` against one
    30-character cell that almost matches runs for minutes inside a
    single re.search, and nothing can interrupt it — the backfill polls
    its cancel flag between batches, and the preview and the named-group
    probe run inside the request."""
    if len(pattern) > _MAX_REGEX_LEN:
        raise ValueError(f"Regex too long ({len(pattern)} > {_MAX_REGEX_LEN} characters)")
    try:
        rx = re.compile(pattern)
    except re.error as e:
        raise ValueError(f"Invalid regex: {e}")
    hazard = rxguard.regex_hazard(pattern)
    if hazard:
        raise ValueError(
            f"This pattern has {hazard}, which can backtrack catastrophically: on one unlucky "
            "value it runs for minutes with no way to stop it. End each part of the repetition "
            r"at a character it cannot match — (\w+\s)* rather than (\w+\s?)*, (\w+\.)+ "
            r"rather than (\w+\.?)+ — or use one class instead of the nesting, [\w\s]* for "
            r"(\w+\s?)*.")
    return rx


def _validate_regex_params(params: dict) -> None:
    pattern = params.get("pattern", "")
    rx = _compile_analyst_regex(pattern)
    name = (params.get("group_name") or "").strip()
    if name and name not in rx.groupindex:
        named = ", ".join(sorted(rx.groupindex)) or "none"
        raise ValueError(f"The pattern has no group called {name!r} — it names: {named}")
    g = int(params.get("group") or 0)
    if g and g > rx.groups:
        raise ValueError(
            f"The pattern has {rx.groups} capture group{'s' if rx.groups != 1 else ''} — group {g} doesn't exist")


def regex_group_names(pattern: str) -> list[str]:
    """The (?P<name>…) groups a pattern declares, in the order they open.

    What "one column per named group" is built from. `groupindex` maps
    name -> number, and the numbers are assigned left to right, so sorting
    by number puts the columns in the order the analyst wrote them rather
    than in alphabetical order — for a path/method/status pattern that is
    the difference between reading the definition and decoding it."""
    rx = _compile_analyst_regex(pattern or "")
    return [name for name, _ in sorted(rx.groupindex.items(), key=lambda kv: kv[1])]


