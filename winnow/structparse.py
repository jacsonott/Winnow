def sniff_kind(values: Iterator | list) -> str | None:
    """'json' | 'xml' | None for a column, from a sample of its values.
    Majority wins; a column has to be mostly one shape before the UI offers
    to take it apart."""
    vals = [str(v) for v in values if v is not None and str(v).strip()]
    if not vals:
        return None
    js = sum(1 for v in vals if load_json(v) is not None)
    if js * 2 > len(vals):
        return "json"
    xm = sum(1 for v in vals if load_xml(v) is not None)
    if xm * 2 > len(vals):
        return "xml"
    return None


def discover_paths(values: list, kind: str) -> list[dict]:
    """Every field found across a sample, with how many of the sampled rows
    had it and one example value.

    Coverage is the number that makes this list usable: a path present in
    3 of 200 rows is a different proposition from one present in 200, and
    ordering by it puts the columns worth making at the top. Sorted by
    coverage, then by path, so the same sample always produces the same
    order — the analyst is ticking checkboxes against this list.
    """
    counts: dict[str, int] = {}
    nonempty: dict[str, int] = {}
    samples: dict[str, str] = {}
    labels: dict[str, str] = {}
    seen_rows = 0
    for raw in values:
        if raw is None or not str(raw).strip():
            continue
        if kind == "json":
            doc = load_json(raw)
            if doc is None:
                continue
            # _leaf_text's utf8_text: a lone surrogate in a value would
            # fail the route's response; one in a key is escaped by the
            # path itself.
            found = [(format_json_path(p), _leaf_text(v)) for p, v in json_leaf_paths(doc)]
        else:
            root = load_xml(raw)
            if root is None:
                continue
            found = xml_leaf_paths(root)
        seen_rows += 1
        for path, sample in dict(found).items():
            counts[path] = counts.get(path, 0) + 1
            if sample != "":
                nonempty[path] = nonempty.get(path, 0) + 1
            if path not in samples and sample:
                samples[path] = sample[:200]
            labels.setdefault(path, suggest_name(path, kind))
    # `count` is "the field is there"; `nonempty` is "there's something in
    # it". They come apart for a container element whose value lives in its
    # attributes — `<TimeCreated SystemTime="..."/>` is present in every row
    # and empty in every row, and a column of blanks is not what ticking a
    # 100%-coverage field should get you. The caller uses nonempty to decide
    # what to preselect; both are reported rather than folded together, so
    # "present but always empty" stays visible instead of vanishing.
    out = [
        {"path": p, "count": n, "coverage": (n / seen_rows) if seen_rows else 0.0,
         "nonempty": nonempty.get(p, 0),
         "sample": samples.get(p, ""), "suggested_name": labels[p]}
        for p, n in counts.items()
    ]
    # Fields with something in them first, then by coverage — the ticking
    # order should match the "is this worth a column" order.
    out.sort(key=lambda r: (-r["nonempty"], -r["count"], r["path"]))
    return out[:MAX_PATHS]


def suggest_name(path: str, kind: str) -> str:
    """A column name from a path. JSON: the FULL dotted path without the
    `$.` — `target.ip`, `items[0].id` — so a document with `target.ip`
    and `source.ip` flattens to two columns that say which is which,
    rather than `ip` and `ip 2`; the analyst who wants shorter names
    edits them in the picker. A Name/Value entry is the exception, and is
    named by its Name (`Properties[Name='UserAgent'].Value` -> UserAgent),
    because there the Name is the field name and the path is plumbing. XML: the last meaningful component, since
    EVTX paths already carry their meaning in the predicate
    (`Data[@Name='TargetUserName']` names itself) and a full element path
    would be unreadable. Collisions with existing columns are the caller's
    problem (store.add_derived_column already refuses them and the batch
    path disambiguates). Always text with a UTF-8 form (utf8_text): a key
    holding a lone surrogate names its column with the escape."""
    return utf8_text(_suggest_name(path, kind))


def _suggest_name(path: str, kind: str) -> str:
    s = str(path)
    # JSON is decided first: the "@" rules below are XML's, and an
    # EvtxECmd payload is full of keys that merely start with "@" — the
    # XML-to-JSON convention for attributes. Sent down the XML branch,
    # $.EventData.Data[0].@Name came out "$.EventData.Data[0]. Name" next
    # to a clean "EventData.Data[0].#text" from its sibling key.
    if kind == "json":
        try:
            segs = parse_json_path(s)
        except ValueError:
            return s
        if not any(not isinstance(seg, int) for seg in segs):
            return s.lstrip("$.")
        # A Name/Value entry names itself, like an XML predicate does:
        # `Properties[Name='UserAgent'].Value` is UserAgent, and the value
        # key is dropped when it is the plain one (Value, #text) — but kept
        # when it says which value (`[Name='X'].NewValue` is X.NewValue).
        last = max((i for i, seg in enumerate(segs) if isinstance(seg, tuple)), default=None)
        if last is not None and str(segs[last][1]).strip():
            out = str(segs[last][1]).strip()
            rest = segs[last + 1:]
            if rest and isinstance(rest[0], str) and rest[0].lower().lstrip("@#") in ("value", "text"):
                rest = rest[1:]
        else:
            out, rest = "", segs
        for seg in rest:
            if isinstance(seg, int):
                out += f"[{seg}]"
            elif isinstance(seg, tuple):
                out += f"[{seg[0]}={_quote_predicate(seg[1])}]"
            else:
                out += ("." if out else "") + str(seg)
        return out
    # `Data[@Name='TargetUserName']` names itself — that predicate value is
    # a better column name than anything its tag or position could give.
    # Read through parse_xml_path, so a value quoted "O'Brien" (or with a
    # doubled quote) names its column the same way 'TargetUserName' does.
    try:
        steps, attr = parse_xml_path(s)
    except ValueError:
        steps, attr = [], None
    if steps and attr is None and isinstance(steps[-1][1], tuple) and str(steps[-1][1][1]).strip():
        return str(steps[-1][1][1]).strip()
    if "@" in s and not s.rstrip().endswith("]"):
        head, _, attr = s.rpartition("@")
        tail = head.rstrip("/").split("/")[-1] if head.strip("/") else ""
        tail = re.sub(r"\[[^\]]*\]$", "", tail)
        return f"{tail} {attr}".strip() if tail else attr
    last = s.rstrip("/").split("/")[-1]
    return re.sub(r"\[\d+\]$", "", last) or s
