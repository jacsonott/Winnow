"""JSON/XML field extraction operations for derived columns.

Log columns that hold a whole nested document in one cell are the norm in
DFIR data — EVTX `EventData`, cloud audit `requestParameters`, EDR
telemetry blobs. The grid can only show that as one long unreadable
string, and you can't sort, filter or group by something buried inside it.
These operations lift one field out into a real column.

They ride the same registry and the same machinery as the timestamp
operations in `timeparse.py` (see its `register_op` docstring — it is
explicitly the seam for this) rather than growing a parallel one, because
what a derived column needs is identical either way: a per-row `parse`,
a params schema, a backfill into the `drv_<id>` sidecar, and a definition
that sessions can carry and recompute. The only thing that differs is what
comes out, so these ops carry `derived_kind: "text"` and
`family: "extract"` — the latter is what keeps them out of the "Add
datetime column" picker, which is a different question the analyst is
asking.

Stdlib only, and imports nothing from the app except the registry itself
and rxguard, the catastrophic-backtracking check it shares with store.py.

**Paths are the analyst's addressing scheme, so they have to survive being
written down.** They go into a column definition, a session file and the
UI, so both syntaxes are text, both round-trip through parse/format, and
both are generated by clicking a node in the detail pane rather than being
typed from scratch:

    JSON   $.user.name    items[0].id    ["odd.key"].value
           ExtendedProperties[Name='UserAgent'].Value
    XML    Event/System/EventID    Provider@Name    Data[2]

XML safety: `<!DOCTYPE ...>` is refused outright rather than parsed.
ElementTree expands internal entities (verified — a billion-laughs payload
parses rather than raising), and cell values here are untrusted evidence
that a plugin author, a suspect or a broken exporter wrote. No log field
this feature targets carries a DOCTYPE, so refusing one costs nothing real
and removes the entire entity-expansion question. There is no network
fetch of external entities either way — ElementTree never resolves them.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
from typing import Any, Iterator

from . import rxguard, timeparse

# A cell big enough to be a denial-of-service against the backfill rather
# than a log field. 8 MB is far past any real EventData blob and still
# parses in well under the time one BATCH of rows takes.
MAX_DOC_BYTES = 8 * 1024 * 1024

# How deep path enumeration walks, and how many distinct paths it will
# report. Both are guards against a pathological document (a deeply
# recursive structure, or a map keyed by GUID with 50,000 entries) turning
# "show me what's in here" into a hang.
MAX_WALK_DEPTH = 24
MAX_PATHS = 400

_DOCTYPE_RE = re.compile(r"<!DOCTYPE", re.IGNORECASE)


def utf8_text(s: str) -> str:
    """`s` as text that has a UTF-8 form — what SQLite stores and what a
    route's JSON body can carry. JSON's "\\udc80" decodes to a lone
    surrogate, which has none: anything holding one fails wherever it is
    next encoded (a batch insert, a response). It is written back as the
    six characters of the escape the document had. store.py uses this one
    for JSON import; plasoread.py, which imports nothing from the app,
    keeps a twin. The ASCII check is the fast path almost every value
    takes."""
    if s.isascii():
        return s
    try:
        s.encode("utf-8")
        return s
    except UnicodeEncodeError:
        return s.encode("utf-8", "backslashreplace").decode("utf-8")


def _has_lone_surrogate(s: str) -> bool:
    return not s.isascii() and any("\ud800" <= ch <= "\udfff" for ch in s)


def _leaf_text(value: Any) -> str:
    """A JSON value at the point extraction stops -> TEXT.

    Same convention as store.py's `_json_leaf_text` (all values are TEXT;
    an object or array is JSON-stringified whole rather than dropped or
    half-flattened), duplicated rather than imported because this module
    stays free of app imports. A JSON `null` becomes an empty cell, not a
    missing one — the field was there and it was null, which is different
    from the field not being present at all (see `_extract_json`).
    """
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        text = json.dumps(value, ensure_ascii=False)
    else:
        text = str(value)
    # JSON can spell half a character: `"\ud83d"` is legal JSON (a
    # truncated emoji, routine in logs that cut a string at a byte count)
    # and json.loads hands back a str holding a lone surrogate, which
    # cannot be written as UTF-8 — so SQLite refused the row and the
    # whole backfill failed on it. utf8_text writes it back as the escape
    # the cell held, the rule JSON import follows too, so one value reads
    # the same whichever way it came in. Not U+FFFD: that makes
    # `evil\udc80.txt` and `evil\udc81.txt` one value, and two keys one
    # column name.
    return utf8_text(text)


# ------------------------------------------------------------- JSON paths

_JSON_TOKEN_RE = re.compile(
    r"""
    \.\s*(?P<dotkey>[^.\[\]"']+)      # .key
    | \[\s*(?P<index>-?\d+)\s*\]      # [0]
    | \[\s*(?P<pkey>@?[A-Za-z_]\w*)\s*=\s*            # [Name='UserAgent']
          (?:'(?P<psq>(?:''|[^'])*)'|"(?P<pdq>(?:""|[^"])*)")\s*\]
    | \[\s*"(?P<dq>(?:\\.|[^"\\])*)"\s*\]   # ["key"]
    | \[\s*'(?P<sq>(?:\\.|[^'\\])*)'\s*\]   # ['key']
    | (?P<barekey>[^.\[\]"']+)        # leading key with no dot
    """,
    re.VERBOSE,
)


def parse_json_path(text: str) -> list:
    """`$.a.b[0]` / `a.b` / `["odd.key"].v` -> ['a', 'b', 0].

    Leading `$` is optional (SQLite's json_extract spells it, most people
    don't). Bracket-quoting is the escape hatch for keys containing a dot
    or a bracket, which dot notation alone can't address — a real shape in
    cloud audit logs, where keys are often URLs or ARNs.

    `[Name='UserAgent']` selects the entry of a list whose `Name` is
    'UserAgent', and comes back as the tuple ('Name', 'UserAgent'). It is
    the JSON twin of the XML predicate `Data[@Name='LogonType']`, quoted
    the same way, and it exists for the same reason: a list of Name/Value
    pairs (an M365 audit record's ExtendedProperties, an EvtxECmd payload's
    `{"@Name": ..., "#text": ...}`) puts its entries in whatever order the
    writer chose, so `[3].Value` means a different field from row to row.
    """
    s = str(text or "").strip()
    if not s:
        raise ValueError("A field path is required")
    if s.startswith("$"):
        s = s[1:]
    out: list = []
    pos = 0
    while pos < len(s):
        if s[pos].isspace():
            pos += 1
            continue
        m = _JSON_TOKEN_RE.match(s, pos)
        if not m or m.end() == pos:
            raise ValueError(f"Can't read the field path at {s[pos:pos + 12]!r}")
        if m.group("index") is not None:
            out.append(int(m.group("index")))
        elif m.group("pkey") is not None:
            want = (m.group("psq").replace("''", "'") if m.group("psq") is not None
                    else m.group("pdq").replace('""', '"'))
            out.append((m.group("pkey"), want))
        else:
            key = m.group("dotkey") or m.group("barekey")
            if key is not None:
                key = key.strip()
            else:
                # A quoted key is taken exactly as written — the quotes are
                # the escape hatch, and a key with edge whitespace (" id ",
                # "name\t") is a real key format_json_path quotes for that.
                raw = m.group("dq") if m.group("dq") is not None else m.group("sq")
                # `\uXXXX` is how format_json_path spells a lone surrogate
                # in a key (one with no UTF-8 form, so it can't be stored
                # or sent as itself); any other backslash escapes the next
                # character, as it always has.
                key = re.sub(r"\\(u[0-9a-fA-F]{4}|.)",
                             lambda e: chr(int(e.group(1)[1:], 16)) if len(e.group(1)) == 5
                             else e.group(1), raw)
            out.append(key)
        pos = m.end()
    if not out:
        raise ValueError(f"Can't read the field path {text!r}")
    return out


def format_json_path(segments: list) -> str:
    """The inverse of parse_json_path, and the form shown in the UI. Keys
    that dot notation can't express unambiguously come back bracket-quoted,
    so format(parse(x)) is always re-parseable. A lone surrogate in a key
    is spelled `\\uXXXX` inside the quotes: the path is stored in a column
    definition and sent through the UI, and neither can hold the
    character itself."""
    out = "$"
    for seg in segments:
        if isinstance(seg, int):
            out += f"[{seg}]"
        elif isinstance(seg, tuple):
            out += f"[{seg[0]}={_quote_predicate(seg[1])}]"
        elif re.fullmatch(r"[^.\[\]\"']+", str(seg)) and str(seg) == str(seg).strip() \
                and not _has_lone_surrogate(str(seg)):
            # Dot notation strips the key it reads, so a key with edge
            # whitespace has to be quoted to survive the round trip.
            out += f".{seg}"
        else:
            quoted = str(seg).replace("\\", "\\\\").replace('"', '\\"')
            if _has_lone_surrogate(quoted):
                quoted = "".join(f"\\u{ord(ch):04x}" if "\ud800" <= ch <= "\udfff" else ch
                                 for ch in quoted)
            out += '["' + quoted + '"]'
    return out


def load_json(value: Any) -> Any:
    """A cell -> a parsed JSON document, or None if it isn't one.

    "JSON" here is wider than the RFC, by exactly what the detail pane lays
    out as a document (detail.js `findLooseDocuments`): a raw line break
    in a string (`strict=False`), and failing that the loose grammar of
    `load_loose` — Python's repr of a list or dict, a trailing comma, an
    unescaped backslash. The pane makes a whole-value document of that
    kind addressable, so this has to read it too, or "Add as a column"
    would fill the column with nothing on every row.
    """
    if value is None:
        return None
    s = str(value).strip()
    if not s or s[0] not in "{[" or len(s) > MAX_DOC_BYTES:
        return None
    try:
        return json.loads(s, strict=False)
    except (ValueError, RecursionError):
        return load_loose(s)


# ------------------------------------------------- documents json refuses
#
# The twin of detail.js's loose parser (`looseValue` / `looseContainer`),
# and it has to accept exactly what that one does: the pane offers a path
# on a whole-value document only when its parser read all of the value,
# and a path offered on a document this one refuses extracts nothing.
# Python's repr of a list, dict, tuple or set; a string in either quote,
# with an r/b/u prefix; a trailing comma; and a short list of bare words.
# Strings are decoded the way JSON and Python both decode them, and an
# escape neither knows (`\U` in `C:\Users`, a lax exporter's unescaped
# backslash) stays as written. Numbers become what json.loads would have
# made of them where it could have; any other number (hex, `1_000`, `1.`)
# stays as its own text, which is what the column will hold.

LOOSE_MAX_DEPTH = 256
# The loose parser runs in Python, not C: about a second per million
# characters of the worst shape (a million one-character items), against
# json.loads' hundredth of that, so it gets an eighth of MAX_DOC_BYTES. The
# pane offers a path on a loose document only up to the same length
# (detail.js LOOSE_MAX_CHARS), counting in UTF-16 units, which is never
# fewer than Python's code points.
LOOSE_MAX_CHARS = 1_000_000
_LOOSE_CLOSERS = {"[": "]", "{": "}", "(": ")"}
_LOOSE_WORDS = {
    "true": True, "True": True, "false": False, "False": False,
    "null": None, "None": None,
    "NaN": float("nan"), "nan": float("nan"),
    "Infinity": float("inf"), "inf": float("inf"),
    "-Infinity": float("-inf"), "-inf": float("-inf"),
}
# One token per match, leading spaces included, so the parse is a loop
# over matches rather than a call per value. The number alternative is
# greedy with nothing after it, as `LOOSE_NUMBER.exec` is in detail.js;
# a number run straight into a letter (`1abc`) is refused by the caller
# rather than backtracked into a shorter one.
_LOOSE_TOKEN = re.compile(
    r"[ \t\r\n]*(?:"
    r"(?P<p>[\[\]{}(),:])"
    r"|(?P<pre>[rRbBuU]{0,2})(?:\"(?P<dq>[^\"\\]*(?:\\.[^\"\\]*)*)\"|'(?P<sq>[^'\\]*(?:\\.[^'\\]*)*)')"
    r"|(?P<num>[-+]?(?:0[xX][\da-fA-F_]+|(?:\d[\d_]*(?:\.[\d_]*)?|\.\d[\d_]*)(?:[eE][-+]?\d+)?j?))"
    r"|(?P<word>-?[A-Za-z_]\w*)"
    r")",
    re.S | re.A,
)
_LOOSE_WORD_CHAR = re.compile(r"\w", re.A)
_LOOSE_INT = re.compile(r"-?(?:0|[1-9]\d*)", re.A)
_LOOSE_FLOAT = re.compile(r"-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][-+]?\d+)?", re.A)
_LOOSE_ESCAPE = re.compile(r"\\(?:u([0-9a-fA-F]{4})|U([0-9a-fA-F]{8})|x([0-9a-fA-F]{2})|(.))", re.S)
_LOOSE_ESCAPES = {"\\": "\\", "'": "'", '"': '"', "/": "/",
                  "n": "\n", "r": "\r", "t": "\t", "b": "\b", "f": "\f"}


def _loose_unescape(body: str) -> str:
    def one(m: re.Match) -> str:
        if m.group(1):
            return chr(int(m.group(1), 16))
        if m.group(2):
            cp = int(m.group(2), 16)
            return chr(cp) if cp <= 0x10FFFF else m.group(0)
        if m.group(3):
            return chr(int(m.group(3), 16))
        return _LOOSE_ESCAPES.get(m.group(4), m.group(0))
    out = _LOOSE_ESCAPE.sub(one, body) if "\\" in body else body
    # `\ud83d\ude00` is one character spelled as two escapes; JSON and
    # JavaScript both join the halves, and a half left alone stays one.
    if not out.isascii() and any("\ud800" <= ch <= "\udfff" for ch in out):
        out = out.encode("utf-16-le", "surrogatepass").decode("utf-16-le", "surrogatepass")
    return out


def _loose_number(text: str) -> Any:
    if _LOOSE_INT.fullmatch(text):
        return int(text)
    if _LOOSE_FLOAT.fullmatch(text):
        return float(text)
    return text


# What a container is waiting for next.
_VALUE_OR_CLOSE, _AFTER_VALUE, _ENTRY_VALUE, _AFTER_ENTRY = range(4)


def load_loose(s: str) -> Any:
    """A whole value in the loose grammar -> a document, or None.

    Lists, tuples and sets come back as lists, and a `{` is a dict if its
    first element is followed by `:` (`{}` is a dict too). A key that isn't
    a string (`{1: 'a'}`, `{None: 0}`) is named by its own text, which is
    also what the pane shows. Written as a loop over tokens with its own
    stack rather than as the pane's recursion, because a flatten runs it
    on every row of the column.
    """
    if not s or s[0] not in "{[" or len(s) > LOOSE_MAX_CHARS:
        return None
    match = _LOOSE_TOKEN.match
    word_char = _LOOSE_WORD_CHAR.match
    # A frame: [close, opener, items, entries, is_dict, state, pending, start]
    # where `pending` is a value read in _VALUE_OR_CLOSE whose role (a key
    # or an item) the next token decides, as (value, key, start).
    stack: list[list] = []
    pos, end = 0, len(s)
    while True:
        m = match(s, pos)
        if m is None:
            return None
        pos = m.end()
        kind = m.lastgroup
        punct = m.group("p") if kind == "p" else None
        frame = stack[-1] if stack else None
        state = frame[5] if frame else _VALUE_OR_CLOSE

        if state in (_AFTER_VALUE, _AFTER_ENTRY):
            if state == _AFTER_VALUE:
                value, key, _ = frame[6]
                frame[6] = None
                if punct == ":" and frame[1] == "{" and not frame[2]:
                    frame[6] = key
                    frame[5] = _ENTRY_VALUE
                    continue
                if frame[4]:
                    return None
                frame[2].append(value)
            if punct == ",":
                frame[5] = _VALUE_OR_CLOSE
                continue
            if punct != frame[0]:
                return None
            done = frame
        elif punct is not None and punct in _LOOSE_CLOSERS:
            if len(stack) >= LOOSE_MAX_DEPTH:
                return None
            stack.append([_LOOSE_CLOSERS[punct], punct, [], {}, False, _VALUE_OR_CLOSE, None, m.start("p")])
            continue
        elif punct is not None:
            if not (frame and state == _VALUE_OR_CLOSE and punct == frame[0]):
                return None
            done = frame
        else:
            # A scalar, which can only be inside a container.
            if frame is None:
                return None
            text = m.group(kind)
            if kind == "num":
                if word_char(s, pos):
                    return None
                value, key, start = _loose_number(text), text, m.start(kind)
            elif kind == "word":
                if text not in _LOOSE_WORDS:
                    return None
                value, key, start = _LOOSE_WORDS[text], text, m.start(kind)
            else:
                pre = m.group("pre")
                value = text if pre and "r" in pre.lower() else _loose_unescape(text)
                key, start = value, m.start("pre")
            if state == _ENTRY_VALUE:
                frame[3][frame[6]] = value
                frame[4] = True
                frame[6] = None
                frame[5] = _AFTER_ENTRY
            else:
                frame[6] = (value, key, start)
                frame[5] = _AFTER_VALUE
            continue

        # `done` just closed: its value goes to the frame around it.
        stack.pop()
        value = done[3] if done[4] or (done[1] == "{" and not done[2]) else done[2]
        if not stack:
            return value if pos == end else None
        outer = stack[-1]
        if outer[5] == _ENTRY_VALUE:
            outer[3][outer[6]] = value
            outer[4] = True
            outer[6] = None
            outer[5] = _AFTER_ENTRY
        else:
            outer[6] = (value, s[done[7]:pos], done[7])
            outer[5] = _AFTER_VALUE


_MISSING = object()


def _walk_json(doc: Any, segments: list) -> Any:
    cur = doc
    for seg in segments:
        if isinstance(seg, int):
            if not isinstance(cur, list):
                return _MISSING
            try:
                cur = cur[seg]
            except IndexError:
                return _MISSING
        elif isinstance(seg, tuple):
            # `[Name='UserAgent']`: the first entry whose Name is that
            # string. Strings only, on both sides — a name the pane shows
            # as text has to be matched as text, and 1.0 and "1.0" are not
            # the same name.
            key, want = seg
            if not isinstance(cur, list):
                return _MISSING
            cur = next((el for el in cur if isinstance(el, dict) and el.get(key) == want
                        and isinstance(el.get(key), str)), _MISSING)
            if cur is _MISSING:
                return _MISSING
        else:
            if not isinstance(cur, dict) or seg not in cur:
                return _MISSING
            cur = cur[seg]
    return cur


# A list of Name/Value pairs, and how to tell one from a list of records.
# The name key is spelled Name or Key in any case, with or without the
# XML-to-JSON `@` (EvtxECmd's `{"@Name": ..., "#text": ...}`); every entry
# has one, they are all different strings, and at least one entry holds
# something value-like beside it: Value, #text, or a key with "value" in
# it (Azure AD's OldValue/NewValue). The last rule is what keeps a list of
# files — `[{"name": "a.exe", "size": 3}]` — positional: a file's name is
# data, not a field name, and a column per file name would be useless.
# detail.js `jsonKvShape` is the twin and has to agree, name for name.
_KV_NAME_KEYS = (re.compile(r"@?name", re.I | re.A), re.compile(r"@?key", re.I | re.A))
# A name that is going to be a column name: some text, short enough to be
# one (store refuses a name over 200), and nothing a path or a column
# definition can't carry — no control characters, and nothing outside the
# BMP, whose JavaScript spelling is two halves.
_KV_NAME_BAD = re.compile("[\x00-\x1f\x7f\ud800-\udfff\U00010000-\U0010ffff]")
_KV_NAME_MAX = 120


def _kv_name_ok(name: Any) -> bool:
    return (isinstance(name, str) and 0 < len(name) <= _KV_NAME_MAX
            and re.search(r"[^ \t\n\r\x0b\x0c]", name) is not None
            and not _KV_NAME_BAD.search(name))


def _kv_value_like(key: str) -> bool:
    k = key.lower().lstrip("@#")
    return k == "text" or "value" in k


def _kv_shape(items: list) -> str | None:
    """The key that names each entry of a Name/Value list, or None."""
    if not items or not all(isinstance(x, dict) and x for x in items):
        return None
    for rx in _KV_NAME_KEYS:
        key = next((k for k in items[0] if rx.fullmatch(k)), None)
        if key is None:
            continue
        names = [x.get(key) for x in items]
        if not all(_kv_name_ok(n) for n in names) or len(set(names)) != len(names):
            continue
        if any(_kv_value_like(k) for x in items for k in x if k != key):
            return key
    return None


def json_leaf_paths(doc: Any) -> list[tuple[list, Any]]:
    """Every addressable leaf in a document, as (segments, value).

    Objects are walked; so are arrays, but only far enough to be useful —
    an array of scalars is a leaf in its own right (a list of IPs is one
    column, not N), while an array of objects is indexed into, because
    that's the shape where the interesting fields live (`Data[0].Name`).
    That asymmetry is deliberate and matches store.py's `_flatten_json`
    reasoning about varying array lengths: index-expanding a scalar list
    would make the offered column set vary row to row for no gain.

    A list of Name/Value pairs (`_kv_shape`) is addressed by name instead
    of by index — `ExtendedProperties[Name='UserAgent'].Value`, which
    suggest_name turns into a column called UserAgent — because its order
    is whatever the writer chose and `[3].Value` is a different field from
    row to row. The Name itself isn't offered: it restates the predicate.
    """
    out: list[tuple[list, Any]] = []

    def walk(value: Any, path: list, depth: int) -> None:
        if len(out) >= MAX_PATHS or depth > MAX_WALK_DEPTH:
            return
        if isinstance(value, dict):
            if not value:
                out.append((path, value))
                return
            for k, v in value.items():
                walk(v, path + [str(k)], depth + 1)
        elif isinstance(value, list):
            name_key = _kv_shape(value)
            if name_key is not None:
                for el in value:
                    at = path + [(name_key, el[name_key])]
                    for k, v in el.items():
                        if k != name_key:
                            walk(v, at + [str(k)], depth + 1)
            elif value and all(isinstance(x, (dict, list)) for x in value):
                for i, v in enumerate(value):
                    walk(v, path + [i], depth + 1)
            else:
                out.append((path, value))
        else:
            out.append((path, value))

    walk(doc, [], 0)
    return out


# The last cell parsed, so a flatten that builds ten columns from one
# column parses each row once rather than ten times: the backfill hands
# every column of a batch the same value object in turn. Matched by
# identity, never by equality, and only for a cell small enough that
# keeping its document alive until the next one costs nothing.
_LAST_DOC: tuple = (None, None)
_LAST_DOC_MAX = 64 * 1024


def _load_json_for_row(value: Any) -> Any:
    global _LAST_DOC
    last = _LAST_DOC
    if value is not None and last[0] is value:
        return last[1]
    doc = load_json(value)
    if isinstance(value, str) and len(value) <= _LAST_DOC_MAX:
        _LAST_DOC = (value, doc)
    return doc


def _extract_json(value: Any, params: dict, state: dict) -> str | None:
    """One row. None means "this row has no such field" — which the
    derived-column machinery counts and can filter to, and which is a
    genuinely different answer from "the field is there and it's empty".
    A JSON `null` is the latter, and comes back as ''."""
    doc = _load_json_for_row(value)
    if doc is None:
        return None
    segments = state.get("segments")
    if segments is None:
        segments = state["segments"] = parse_json_path(params["path"])
    found = _walk_json(doc, segments)
    if found is _MISSING:
        return None
    return _leaf_text(found)


# -------------------------------------------------------------- XML paths

def _structural(s: str):
    """(index, char, bracket depth) for every character of a path that is
    syntax rather than a predicate's quoted value. Predicate values are
    analyst data — file paths, URLs, "a]b", "c@d" — so a `/`, `]` or `@`
    inside the quotes must not split, close or select anything. A doubled
    quote ('') simply closes and reopens, so it needs no case of its own."""
    depth, quote = 0, None
    for i, ch in enumerate(s):
        if quote:
            if ch == quote:
                quote = None
            continue
        if ch in "'\"" and depth:
            quote = ch
            continue
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth = max(0, depth - 1)
        yield i, ch, depth


def _split_steps(s: str) -> list[str]:
    """`a/b[@N='x/y']/c` -> ['a', "b[@N='x/y']", 'c'] — a plain split would
    cut the predicate in half, and predicate values are analyst data
    (file paths, URLs) that routinely contain slashes."""
    cuts = [i for i, ch, depth in _structural(s) if ch == "/" and depth == 0]
    out, start = [], 0
    for i in cuts:
        out.append(s[start:i])
        start = i + 1
    out.append(s[start:])
    return out


def _trailing_at(s: str) -> int | None:
    """Index of the `@` that selects an attribute — the last one at bracket
    depth zero — or None if the path selects an element's text."""
    found = None
    for i, ch, depth in _structural(s):
        if ch == "@" and depth == 0:
            found = i
    return found


_XML_STEP_RE = re.compile(
    r"""^(?P<tag>[^\[\]@/]+)
    (?:\[
        (?: (?P<index>\d+)
          | @(?P<pattr>[\w:.-]+)\s*=\s*(?:'(?P<sq>(?:[^']|'')*)'|"(?P<dq>(?:[^"]|"")*)")
        )
    \])?$""",
    re.VERBOSE,
)


def parse_xml_path(text: str) -> tuple[list[tuple[str, Any]], str | None]:
    """`Event/System/EventID` -> ([('Event', 0), ('System', 0),
    ('EventID', 0)], None); a trailing `@Name` is returned separately as
    the attribute to read instead of the element's text.

    A step selects among same-named siblings either positionally (`[n]`,
    0-based) or by attribute (`[@Name='TargetUserName']`, the XPath
    spelling). The predicate form exists because of Windows event logs,
    where the entire payload is `<Data Name="TargetUserName">jacson</Data>`
    repeated — addressing that by position gives you a column called
    "Data[4]" whose meaning shifts between event IDs, while addressing it
    by name gives you a column called "TargetUserName" that means the same
    thing in every row that has one. `discover_paths` prefers the
    predicate form for exactly that reason.

    Namespaces are matched on the local name (see `_local`), because a log
    field's fully-qualified `{http://...}Data` is noise the analyst never
    wants to type or read.
    """
    s = str(text or "").strip()
    if not s:
        raise ValueError("A field path is required")
    attr = None
    # Only a trailing `@attr` selects an attribute. An `@` inside brackets
    # belongs to a predicate (`Data[@Name='X']`) and must not be split on —
    # partitioning at the first `@` turned that path into the element
    # `Event/EventData/Data[` and lost the rest.
    at = _trailing_at(s)
    if at is not None:
        attr = s[at + 1:].strip()
        s = s[:at].strip()
        if not attr:
            raise ValueError("Expected an attribute name after '@'")
    steps: list[tuple[str, Any]] = []
    for raw in _split_steps(s):
        raw = raw.strip()
        if not raw:
            continue
        m = _XML_STEP_RE.match(raw)
        if not m:
            raise ValueError(f"Can't read the element path at {raw!r}")
        if m.group("pattr"):
            pval = (m.group("sq").replace("''", "'") if m.group("sq") is not None
                    else m.group("dq").replace('""', '"'))
            sel: Any = (m.group("pattr"), pval)
        else:
            sel = int(m.group("index") or 0)
        steps.append((m.group("tag").strip(), sel))
    if not steps and attr is None:
        raise ValueError(f"Can't read the element path {text!r}")
    return steps, attr


def _quote_predicate(value: Any) -> str:
    """Single quotes as XPath writes them, double when the value holds an
    apostrophe (Name="O'Brien"), and a doubled quote when it holds both —
    XPath 2.0's escape; parse_xml_path and parse_json_path read all three.
    A value spliced in bare broke the parse, and discovery then offered
    (pre-ticked, at 100%) a path that failed the whole flatten batch."""
    v = str(value)
    if "'" not in v:
        return f"'{v}'"
    if '"' not in v:
        return f'"{v}"'
    return "'" + v.replace("'", "''") + "'"


def _format_step(tag: str, sel: Any) -> str:
    if isinstance(sel, tuple):
        return f"{tag}[@{sel[0]}={_quote_predicate(sel[1])}]"
    return tag if sel == 0 else f"{tag}[{sel}]"


def format_xml_path(steps: list[tuple[str, Any]], attr: str | None = None) -> str:
    out = "/".join(_format_step(t, sel) for t, sel in steps)
    return f"{out}@{attr}" if attr else out


def _local(tag: str) -> str:
    """`{http://schemas...}Data` -> `Data`."""
    return tag.rsplit("}", 1)[-1] if "}" in tag else tag


def load_xml(value: Any) -> "ET.Element | None":
    """A cell -> a parsed element, or None if it isn't usable XML.

    Two tolerances that matter on real data: a `<?xml?>` prolog is fine,
    and a *fragment* with several top-level elements (common when a field
    holds a slice of a larger document) is retried inside a synthetic root
    rather than rejected. A DOCTYPE is refused — see the module docstring.
    """
    if value is None:
        return None
    s = str(value).strip()
    if not s or not s.startswith("<") or len(s) > MAX_DOC_BYTES:
        return None
    if _DOCTYPE_RE.search(s):
        return None
    # ValueError as well as ParseError: expat is fed UTF-8, so a str it
    # cannot encode (one holding a lone surrogate) raises
    # UnicodeEncodeError before parsing starts. Not XML either way.
    try:
        return ET.fromstring(s)
    except (ET.ParseError, ValueError):
        pass
    try:
        # Wrapping re-parses the prolog as content, so drop it first.
        body = re.sub(r"^<\?xml[^>]*\?>", "", s).strip()
        return ET.fromstring(f"<winnow-fragment>{body}</winnow-fragment>")
    except (ET.ParseError, ValueError):
        return None


def _xml_root_steps(root: ET.Element) -> list[str]:
    """The synthetic fragment wrapper is an implementation detail — paths
    are written against what was actually in the cell."""
    return [] if root.tag == "winnow-fragment" else [_local(root.tag)]


def _attr_value(node: ET.Element, name: str) -> str | None:
    for k, v in node.attrib.items():
        if _local(k) == name:
            return v
    return None


def _xml_find(root: ET.Element, steps: list[tuple[str, Any]]) -> "ET.Element | None":
    if not steps:
        return root
    # A path written against a real document starts at its root element;
    # one written against a fragment starts at the first of its children.
    if root.tag != "winnow-fragment":
        tag, sel = steps[0]
        if _local(root.tag) != tag or sel != 0:
            return None
        cur, rest = root, steps[1:]
    else:
        cur, rest = root, steps
    for tag, sel in rest:
        matches = [c for c in cur if _local(c.tag) == tag]
        if isinstance(sel, tuple):
            attr, want = sel
            matches = [c for c in matches if _attr_value(c, attr) == want]
            if not matches:
                return None
            cur = matches[0]
        else:
            if sel >= len(matches):
                return None
            cur = matches[sel]
    return cur


# Attribute names that identify a repeated element rather than describing
# it. Checked case-insensitively and in order — `Name` first because that
# is what Windows event logs use, which is most of the XML this feature
# will ever meet.
_ID_ATTRS = ("name", "key", "id")


def _sibling_selectors(kids: list[ET.Element]) -> list[Any]:
    """How to address each child among its same-named siblings: positional
    normally, but by attribute when a repeated element carries one that
    tells its instances apart.

    This is what turns an EVTX `EventData` block into columns called
    `TargetUserName` and `LogonType` instead of `Data[4]` and `Data[8]` —
    positional paths through a repeated element are not stable across
    event IDs, so a column built on one means something different from row
    to row. Only used when the attribute is present on *every* one of the
    same-named siblings and its values are distinct, since otherwise the
    predicate wouldn't identify a single element either.
    """
    groups: dict[str, list[int]] = {}
    for i, c in enumerate(kids):
        groups.setdefault(_local(c.tag), []).append(i)

    sel: list[Any] = [0] * len(kids)
    for tag, idxs in groups.items():
        chosen = None
        if len(idxs) > 1:
            for want in _ID_ATTRS:
                vals = [_attr_ci(kids[i], want) for i in idxs]
                named = [_real_attr_name(kids[i], want) for i in idxs]
                if all(v is not None for v in vals) and len(set(vals)) == len(vals):
                    chosen = (named[0], vals)
                    break
        if chosen:
            attr, vals = chosen
            for slot, i in enumerate(idxs):
                sel[i] = (attr, vals[slot])
        else:
            for slot, i in enumerate(idxs):
                sel[i] = slot
    return sel


def _attr_ci(node: ET.Element, lowered: str) -> str | None:
    """Attribute lookup by lowercased local name — used only to *probe* for
    an identifying attribute. The path that comes out records the
    attribute's real spelling (see _real_attr_name), and matching a written
    path back against a document stays case-sensitive, as XML requires."""
    for k, v in node.attrib.items():
        if _local(k).lower() == lowered:
            return v
    return None


def _real_attr_name(node: ET.Element, lowered: str) -> str:
    """The attribute's own spelling, so a path round-trips against the
    document rather than against our lowercased probe."""
    for k in node.attrib:
        if _local(k).lower() == lowered:
            return _local(k)
    return lowered


def xml_leaf_paths(root: ET.Element) -> list[tuple[str, str]]:
    """Every addressable value in a document, as (path, sample text) —
    element texts and attributes both, since which of the two an EVTX-style
    `<Data Name="TargetUserName">jacson</Data>` puts the useful part in
    depends entirely on who wrote the exporter."""
    out: list[tuple[str, str]] = []
    base = _xml_root_steps(root)

    def walk(node: ET.Element, steps: list[tuple[str, Any]], depth: int) -> None:
        if len(out) >= MAX_PATHS or depth > MAX_WALK_DEPTH:
            return
        here = format_xml_path(steps)
        # The attribute that selected this element restates the predicate
        # (`Data[@Name='LogonType']@Name` is always 'LogonType'), so it's
        # noise in the picker rather than a field worth a column.
        selector = steps[-1][1] if steps and isinstance(steps[-1][1], tuple) else None
        for name, val in node.attrib.items():
            if selector and _local(name) == selector[0] and val == selector[1]:
                continue
            out.append((f"{here}@{_local(name)}" if here else f"@{_local(name)}", val))
        kids = list(node)
        if not kids:
            text = (node.text or "").strip()
            if here:
                out.append((here, text))
            return
        for child, sel in zip(kids, _sibling_selectors(kids)):
            walk(child, steps + [(_local(child.tag), sel)], depth + 1)

    walk(root, [(t, 0) for t in base], 0)
    return out


def _extract_xml(value: Any, params: dict, state: dict) -> str | None:
    root = load_xml(value)
    if root is None:
        return None
    parsed = state.get("xpath")
    if parsed is None:
        parsed = state["xpath"] = parse_xml_path(params["path"])
    steps, attr = parsed
    node = _xml_find(root, steps)
    if node is None:
        return None
    if attr:
        for name, val in node.attrib.items():
            if _local(name) == attr:
                return val
        return None
    return (node.text or "").strip()


